/**
 * Snap the delivery routes to real streets, once, with OSRM.
 *
 * Reads the waypoints in src/data/routeWaypoints.ts, asks the public OSRM demo
 * router (router.project-osrm.org, OpenStreetMap data) for the driving route
 * through them, lightly simplifies each line and writes src/data/routeGeometry.ts.
 * The app only reads that file: the map never calls OSRM at runtime.
 *
 * Run:  node scripts/snap-routes-osrm.mjs
 * Needs Node 22.18+ (loads the .ts waypoints file directly).
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { ROUTE_WAYPOINTS } from "../src/data/routeWaypoints.ts";

const OSRM = "https://router.project-osrm.org/route/v1/driving";
const OUT = fileURLToPath(new URL("../src/data/routeGeometry.ts", import.meta.url));
/** ~3 m: drops points on straight road, keeps every corner. */
const TOLERANCE = 0.00003;

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

/** Ramer–Douglas–Peucker on lon/lat (fine at city scale). */
function simplify(points, tolerance) {
  if (points.length < 3) return points;
  const [ax, ay] = points[0];
  const [bx, by] = points[points.length - 1];
  const dx = bx - ax;
  const dy = by - ay;
  const length = Math.hypot(dx, dy) || 1;
  let farthest = 0;
  let index = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const [px, py] = points[i];
    const distance = Math.abs(dy * px - dx * py + bx * ay - by * ax) / length;
    if (distance > farthest) {
      farthest = distance;
      index = i;
    }
  }
  if (farthest <= tolerance) return [points[0], points[points.length - 1]];
  return [...simplify(points.slice(0, index + 1), tolerance).slice(0, -1), ...simplify(points.slice(index), tolerance)];
}

const round = ([lng, lat]) => [Number(lng.toFixed(5)), Number(lat.toFixed(5))];

const paths = {};
const summary = [];
for (const [id, waypoints] of Object.entries(ROUTE_WAYPOINTS)) {
  const coordinates = waypoints.map(([lng, lat]) => `${lng},${lat}`).join(";");
  const url = `${OSRM}/${coordinates}?overview=full&geometries=geojson&continue_straight=true`;
  const response = await fetch(url, { headers: { "User-Agent": "joja-cola-demo/1.0 (one-off route snapping)" } });
  if (!response.ok) throw new Error(`${id}: OSRM HTTP ${response.status}`);
  const body = await response.json();
  if (body.code !== "Ok" || !body.routes?.length) throw new Error(`${id}: OSRM ${body.code} ${body.message ?? ""}`);
  const route = body.routes[0];
  const line = simplify(route.geometry.coordinates, TOLERANCE).map(round);
  paths[id] = line;
  summary.push(`${id}: ${route.geometry.coordinates.length} → ${line.length} points, ${(route.distance / 1000).toFixed(1)} km`);
  // The demo server allows about one request per second.
  await sleep(1100);
}

const file = `// Generated by scripts/snap-routes-osrm.mjs — do not edit by hand.
// Road geometry from the OSRM demo router, © OpenStreetMap contributors (ODbL).
export const ROAD_PATHS: Record<string, [number, number][]> = ${JSON.stringify(paths)};
`;
writeFileSync(OUT, file);
console.log(summary.join("\n"));
console.log(`wrote ${OUT}`);
